package com.duriseo.server.common.api

import org.springframework.http.HttpStatus

/**
 * API 오류 코드. 이름과 상태는 Docs `docs/API.md` 5장 표와 같아야 한다.
 * 새 코드는 API.md에 먼저 생긴 뒤에만 추가한다.
 */
enum class ErrorCode(val status: HttpStatus) {
	VALIDATION_FAILED(HttpStatus.BAD_REQUEST),
	DATE_OUT_OF_RANGE(HttpStatus.BAD_REQUEST),
	INVALID_TARGET(HttpStatus.BAD_REQUEST),

	TOKEN_EXPIRED(HttpStatus.UNAUTHORIZED),
	SESSION_INVALID(HttpStatus.UNAUTHORIZED),
	SESSION_REPLACED(HttpStatus.UNAUTHORIZED),
	SOCIAL_TOKEN_INVALID(HttpStatus.UNAUTHORIZED),
	WEBHOOK_UNAUTHORIZED(HttpStatus.UNAUTHORIZED),

	NOT_AUTHOR(HttpStatus.FORBIDDEN),
	GUEST_NOT_ALLOWED(HttpStatus.FORBIDDEN),
	GUEST_ONLY(HttpStatus.FORBIDDEN),

	NOT_FOUND(HttpStatus.NOT_FOUND),
	INVITE_NOT_FOUND(HttpStatus.NOT_FOUND),
	SOCIAL_NOT_REGISTERED(HttpStatus.NOT_FOUND),

	NO_IMPORT_PENDING(HttpStatus.CONFLICT),
	INVITE_EXPIRED(HttpStatus.CONFLICT),
	INVITE_USED(HttpStatus.CONFLICT),
	INVITE_SELF(HttpStatus.CONFLICT),
	INVITE_UNAVAILABLE(HttpStatus.CONFLICT),
	ALREADY_COUPLED(HttpStatus.CONFLICT),
	NOT_COUPLE(HttpStatus.CONFLICT),
	SOCIAL_ALREADY_USED(HttpStatus.CONFLICT),

	IMAGE_TOO_LARGE(HttpStatus.CONTENT_TOO_LARGE),
	IMAGE_TYPE_NOT_ALLOWED(HttpStatus.UNSUPPORTED_MEDIA_TYPE),

	INVITE_RATE_LIMITED(HttpStatus.TOO_MANY_REQUESTS),
	INVITE_REISSUE_TOO_SOON(HttpStatus.TOO_MANY_REQUESTS),

	INTERNAL_ERROR(HttpStatus.INTERNAL_SERVER_ERROR),
}
